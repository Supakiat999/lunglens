const EN_TRANSLATION_KEYS = Object.keys(EN_TRANSLATIONS).sort((a, b) => b.length - a.length);
const I18N_ORIGINAL_TEXT = new WeakMap();
const I18N_ORIGINAL_ATTRS = new WeakMap();
const I18N_ATTRS = ["aria-label", "title", "placeholder"];

function currentLang() {
  try { return state?.lang === "en" ? "en" : "th"; } catch (e) { return "th"; }
}

function t(key, vars = {}, lang = currentLang()) {
  const template = lang === "en" ? (I18N_UI.en[key] || key) : key;
  return String(template).replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? "");
}

function tr(value, lang = currentLang()) {
  if (value == null || lang !== "en") return value;
  const source = String(value);
  if (EN_TRANSLATIONS[source]) return EN_TRANSLATIONS[source];
  let output = source;
  for (const key of EN_TRANSLATION_KEYS) {
    if (output.includes(key)) output = output.split(key).join(EN_TRANSLATIONS[key]);
  }
  return output;
}

function formatDate(value, { dateTime = false } = {}) {
  const locale = currentLang() === "en" ? "en-GB" : "th-TH";
  const options = dateTime
    ? { year: "numeric", month: "short", day: "numeric", hour: "2-digit", minute: "2-digit" }
    : { year: "numeric", month: "long", day: "numeric" };
  return new Intl.DateTimeFormat(locale, options).format(new Date(value));
}

function localizeSubtree(root, lang = currentLang()) {
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    if (!I18N_ORIGINAL_TEXT.has(node)) I18N_ORIGINAL_TEXT.set(node, node.nodeValue);
    const original = I18N_ORIGINAL_TEXT.get(node);
    node.nodeValue = lang === "en" ? tr(original, "en") : original;
  }
  const elements = root.nodeType === 1 ? [root, ...root.querySelectorAll("*")] : [...root.querySelectorAll("*")];
  for (const el of elements) {
    if (!I18N_ORIGINAL_ATTRS.has(el)) {
      const original = {};
      for (const attr of I18N_ATTRS) if (el.hasAttribute(attr)) original[attr] = el.getAttribute(attr);
      I18N_ORIGINAL_ATTRS.set(el, original);
    }
    const original = I18N_ORIGINAL_ATTRS.get(el);
    for (const attr of Object.keys(original)) el.setAttribute(attr, lang === "en" ? tr(original[attr], "en") : original[attr]);
  }
}

